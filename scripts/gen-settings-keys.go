//go:build ignore

// gen-settings-keys writes settings_keys_gen.go from the settings index.
//
// Run it with:
//
//	go run scripts/gen-settings-keys.go
//
// or `make settings-keys`. The generated constants let a handler read a key
// through a name the compiler checks, and the guard in settings_keys_test.go
// fails when the index and the file fall out of step.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/buzzqw/gextto"
)

// constantName turns a settings key into a Go identifier:
// torrent_dead_swarm_blocklist_days -> settingTorrentDeadSwarmBlocklistDays.
func constantName(key string) string {
	parts := strings.FieldsFunc(key, func(r rune) bool {
		return r == '_' || r == '-' || r == '.' || r == ' '
	})
	var out strings.Builder
	out.WriteString("setting")
	for _, part := range parts {
		if part == "" {
			continue
		}
		out.WriteString(strings.ToUpper(part[:1]))
		out.WriteString(part[1:])
	}
	return out.String()
}

func main() {
	keys := gextto.SettingsIndexKeys()
	if len(keys) == 0 {
		fmt.Fprintln(os.Stderr, "the settings index is empty")
		os.Exit(1)
	}
	seen := make(map[string]string, len(keys))
	var body bytes.Buffer
	body.WriteString(`// Code generated by "go run scripts/gen-settings-keys.go" from the settings
// index in uiweb_settings.go; DO NOT EDIT.
//
// Every key the settings page shows has a constant here, so a handler reads
// the same name the index declares and a typo cannot compile.

package gextto

const (
`)
	for _, key := range keys {
		name := constantName(key)
		if other, ok := seen[name]; ok {
			fmt.Fprintf(os.Stderr, "keys %q and %q both become %s\n", other, key, name)
			os.Exit(1)
		}
		seen[name] = key
		fmt.Fprintf(&body, "\t%s = %q\n", name, key)
	}
	body.WriteString(")\n\n// settingKeyNames lists every key of the settings page, in index order.\nvar settingKeyNames = []string{\n")
	for _, key := range keys {
		fmt.Fprintf(&body, "\t%q,\n", key)
	}
	body.WriteString("}\n")

	formatted, err := format.Source(body.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "format: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile("settings_keys_gen.go", formatted, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("settings_keys_gen.go: %d keys\n", len(keys))
}
